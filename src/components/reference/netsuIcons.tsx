import type { ComponentType } from "react";

import { NetsuIcon } from "@/components/ui/netsu-icon";

/** What a registry entry draws with: the subset of icon props that lucide icons and NetsuIcon share, plus the NetsuIcon state. */
export type GlyphProps = { className?: string; mode?: string; busy?: boolean; on?: boolean };
export type Glyph = ComponentType<GlyphProps>;

/** A fixed NetsuIcon as a component, for the registries (`PINNED_BUTTONS`, `ARRANGE`...) that store a component per entry. */
function glyph(name: string): Glyph {
  return function NamedGlyph(props) {
    return <NetsuIcon name={name} {...props} />;
  };
}

